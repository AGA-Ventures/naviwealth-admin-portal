create table if not exists public.admin_users (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  email text not null check (char_length(email) between 3 and 254),
  role text not null default 'facilitator'
    check (role in ('owner', 'admin', 'facilitator', 'viewer')),
  status text not null default 'invited'
    check (status in ('active', 'invited', 'suspended')),
  last_active_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists admin_users_email_unique
  on public.admin_users (lower(email));

create index if not exists admin_users_status_role_idx
  on public.admin_users (status, role);

drop trigger if exists admin_users_set_updated_at on public.admin_users;
create trigger admin_users_set_updated_at
before update on public.admin_users
for each row execute function private.set_updated_at();

alter table public.admin_users enable row level security;

revoke all on table public.admin_users from anon, authenticated;
revoke all on sequence public.admin_users_id_seq from anon, authenticated;
grant all on table public.admin_users to service_role;
grant usage, select on sequence public.admin_users_id_seq to service_role;

