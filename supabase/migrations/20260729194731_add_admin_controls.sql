create table if not exists public.game_settings (
  id smallint primary key default 1 check (id = 1),
  default_players integer not null default 4
    check (default_players between 2 and 12),
  default_rounds integer not null default 12
    check (default_rounds between 4 and 40),
  starting_balance integer not null default 25000
    check (starting_balance between 1000 and 1000000),
  turn_seconds integer not null default 60
    check (turn_seconds between 15 and 600),
  market_volatility text not null default 'balanced'
    check (market_volatility in ('low', 'balanced', 'high')),
  auto_rotate_events boolean not null default true,
  allow_negative_balance boolean not null default false,
  enable_loans boolean not null default true,
  require_facilitator boolean not null default true,
  updated_by text not null default 'System',
  updated_at timestamptz not null default now()
);

