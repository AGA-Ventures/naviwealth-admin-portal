create schema if not exists private;

create table if not exists public.datasets (
  id integer generated by default as identity primary key,
  name text not null,
  kind text not null check (kind in ('event', 'stock')),
  description text not null default '',
  status text not null default 'draft'
    check (status in ('draft', 'ready', 'archived')),
  member_ids integer[] not null default '{}'::integer[],
  item_count integer generated always as (cardinality(member_ids)) stored,
  reuse_count integer not null default 0 check (reuse_count >= 0),
  validation_state text not null default 'valid'
    check (validation_state in ('valid', 'warning')),
  last_used_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists datasets_name_unique
  on public.datasets (lower(name));

create index if not exists datasets_updated_at_idx
  on public.datasets (updated_at desc);

create or replace function private.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists datasets_set_updated_at on public.datasets;
create trigger datasets_set_updated_at
before update on public.datasets
for each row execute function private.set_updated_at();

alter table public.datasets enable row level security;

revoke all on table public.datasets from anon, authenticated;
revoke all on sequence public.datasets_id_seq from anon, authenticated;
revoke all on function private.set_updated_at() from public;
grant all on table public.datasets to service_role;
grant usage, select on sequence public.datasets_id_seq to service_role;
grant usage on schema private to service_role;
grant execute on function private.set_updated_at() to service_role;

