function eventAgeTypeBreakdown(records: StoredEventRecord[]) {
  const order: EventCategory[] = [
    "cashflow",
    "capital-gain",
    "expenses",
    "market",
  ];
  const labels: Record<EventCategory, string> = {
    cashflow: "Cash Flow",
    "capital-gain": "Capital Gain",
    expenses: "Expenses",
    market: "Market",
  };
  const counts = new Map<EventCategory, number>();

  for (const record of records) {
    const category = eventTypeTone(record.data.Type);
    counts.set(category, (counts.get(category) ?? 0) + 1);
  }

  return order.flatMap((category) => {
    const count = counts.get(category) ?? 0;
    return count > 0 ? [{ category, label: labels[category], count }] : [];
  });
}

function validateEventAgeSet(records: StoredEventRecord[]) {
  const categories = records.map((record) =>
    eventAgeSetCategory(record.data.Type),
  );
  const cashFlowCount = categories.filter(
    (category) => category === "cashflow",
  ).length;
  const capitalGainCount = categories.filter(
    (category) => category === "capital-gain",
  ).length;

  if (records.length === 0) {
    return {
      complete: false,
      missingType: null,
      message: "Add one Market or Expenses row, or a Cash Flow and Capital Gain pair.",
      shortMessage: "missing event",
    };
  }

  if (records.length === 1 && categories[0] === "cashflow") {
    return {
      complete: false,
      missingType: "Capital Gain",
      message: "Cash Flow must be paired with Capital Gain in the same Age Set.",
      shortMessage: "needs Capital Gain",
    };
  }

  if (records.length === 1 && categories[0] === "capital-gain") {
    return {
      complete: false,
      missingType: "Cash Flow",
      message: "Capital Gain must be paired with Cash Flow in the same Age Set.",
      shortMessage: "needs Cash Flow",
    };
  }

  if (
    records.length === 1 &&
    (categories[0] === "market" || categories[0] === "expenses")
  ) {
    return {
      complete: true,
      missingType: null,
      message: "Single Market or Expenses row is complete.",
      shortMessage: "complete",
    };
  }

  if (
    records.length === 2 &&
    cashFlowCount === 1 &&
    capitalGainCount === 1
  ) {
    return {
      complete: true,
      missingType: null,
      message: "Cash Flow and Capital Gain are paired.",
      shortMessage: "complete",
    };
  }

  const standaloneCount = categories.filter(
    (category) => category === "market" || category === "expenses",
  ).length;
  const message =
    standaloneCount > 0
      ? "Market and Expenses must each occupy an Age Set by themselves."
      : "Use exactly one Cash Flow row with one Capital Gain row in this Age Set.";

  return {
    complete: false,
    missingType: null,
    message,
    shortMessage: "invalid row mix",
  };
}

function eventAgeSetCategory(type: string | undefined): EventCategory | "unknown" {
  const normalized = type?.trim().toLowerCase();
  if (normalized === "capital gain") return "capital-gain";
  if (normalized === "cash flow" || normalized === "cashflow") {
    return "cashflow";
  }
  if (normalized === "expenses" || normalized === "expense") {
    return "expenses";
  }
  if (normalized === "market") return "market";
  return "unknown";
}

function eventTypeTone(type: string | undefined): EventCategory {
  const normalized = type?.trim().toLowerCase();
  if (normalized === "capital gain") return "capital-gain";
  if (normalized === "cash flow" || normalized === "cashflow") {
    return "cashflow";
  }
  if (normalized === "expenses" || normalized === "expense") {
    return "expenses";
  }
  return "market";
}

