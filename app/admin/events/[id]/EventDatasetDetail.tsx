  async function removeStoredEventRecord(record: StoredEventRecord) {
    if (
      !window.confirm(
        `Remove row ${String(record.rowNumber).padStart(2, "0")} · ${eventRecordTitle(record.data)}? This cannot be undone.`,
      )
    ) {
      return;
    }

    setRemovingEventId(record.id);
    try {
      const response = await fetch(`/api/event-records/${record.id}`, {
        method: "DELETE",
      });
      const payload = (await response.json()) as {
        deletedRecord?: StoredEventRecord;
        records?: StoredEventRecord[];
        error?: string;
      };
      if (!response.ok || !payload.deletedRecord || !payload.records) {
        throw new Error(payload.error ?? "The event row could not be removed.");
      }
      setEventRecords(payload.records);
      setSelectedStoredEvent((current) =>
        current?.id === record.id ? null : current,
      );
      const changedAt = new Date().toISOString();
      setDataset((current) =>
        current
          ? {
              ...current,
              memberIds: payload.records!.map((item) => item.id),
              itemCount: payload.records!.length,
              updatedAt: changedAt,
              lastUpdatedBy: {
                name: user.name,
                email: user.email,
                role: user.role,
                action: "event_record.delete",
                at: changedAt,
              },
            }
          : current,
      );
      setToast(
        `Removed ${eventRecordTitle(payload.deletedRecord.data)}. Remaining rows were renumbered.`,
      );
    } catch (removeError) {
      setToast(
        removeError instanceof Error
          ? removeError.message
          : "The event row could not be removed.",
      );
    } finally {
      setRemovingEventId(null);
    }
  }

  function openNewEventRow(
    age: string,
    setNumber: string,
    missingType: string,
    records: StoredEventRecord[],
    trigger: HTMLElement,
    canChooseType = false,
  ) {
    const targetAge = Number(age);
    const targetSet = Number(setNumber);
    const previousRecord = [...eventRecords]
      .sort((left, right) => left.rowNumber - right.rowNumber)
      .filter((record) => {
        const recordAge = Number(record.data.Age?.trim());
        const recordSet = Number(eventAgeSetNumber(record.data));
        return (
          Number.isFinite(targetAge) &&
          Number.isFinite(recordAge) &&
          (recordAge < targetAge ||
            (recordAge === targetAge && recordSet < targetSet))
        );
      })
      .at(-1);
    const insertAfterRowNumber =
      records.length > 0
        ? Math.max(...records.map((record) => record.rowNumber))
        : (previousRecord?.rowNumber ?? 0);
    const template =
      records.at(-1) ??
      previousRecord ??
      eventRecords.find((record) => record.rowNumber > insertAfterRowNumber) ??
      eventRecords[0];
    if (!template) {
      setToast("Add an imported event before creating an Age Set row.");
      return;
    }
    eventTriggerRef.current = trigger;
    setNewEventRow({
      age,
      setNumber,
      missingType,
      canChooseType,
      insertAfterRowNumber,
      sourceFile: template.sourceFile,
      data: createNewEventRecordData(
        template.data,
        age,
        setNumber,
        missingType,
      ),
    });
  }

