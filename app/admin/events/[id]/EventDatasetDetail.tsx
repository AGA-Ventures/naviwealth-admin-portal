function parseEventDatasetIdentity(datasetName: string) {
  const match = datasetName.match(
    /^(.*?)\s*·\s*Ages\s+(\d+)\s*[–—-]\s*(\d+)\s*$/i,
  );
  const startingAge = Number(match?.[2]);
  return {
    name: match?.[1]?.trim() || datasetName.trim(),
    startingAge:
      Number.isInteger(startingAge) && startingAge >= 1 ? startingAge : 25,
  };
}

function formatEventDatasetName(name: string, startingAge: number) {
  const trimmedName = name.trim();
  return `${trimmedName} · Ages ${startingAge}–${
    startingAge + expectedAgeCount
  }`;
}

function formatWindow(startSeconds: number, endSeconds: number) {
  return `${formatClock(startSeconds)}–${formatClock(endSeconds)}`;
}

function formatClock(seconds: number) {
  const minutes = Math.floor(seconds / 60);
  const remaining = seconds % 60;
  return `${String(minutes).padStart(2, "0")}:${String(remaining).padStart(2, "0")}`;
}

function formatDate(value: string) {
  const date = parseDatabaseDate(value);
  if (!date) return "Recently";
  return new Intl.DateTimeFormat("en-MY", {
    day: "numeric",
    month: "short",
    year: "numeric",
  }).format(date);
}

function relativeDate(value: string) {
  const date = parseDatabaseDate(value);
  if (!date) return "recently";
  const minutes = Math.max(
    0,
    Math.floor((Date.now() - date.getTime()) / 60_000),
  );
  if (minutes < 1) return "just now";
  if (minutes < 60) return `${minutes}m ago`;
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return `${hours}h ago`;
  return `${Math.floor(hours / 24)}d ago`;
}

function parseDatabaseDate(value: string) {
  const date = new Date(`${value.replace(" ", "T")}Z`);
  return Number.isNaN(date.getTime()) ? null : date;
}

function initials(name: string) {
  return name
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((part) => part[0]?.toUpperCase())
    .join("");
}
